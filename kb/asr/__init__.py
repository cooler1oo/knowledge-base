"""语音识别层：把一段长音频切成短段分别解码，再拼回完整文本。

为什么单独一层而不是塞进 `kb/extract/`：抓取层解决「怎么从一个 URL 拿到内容」，
本层解决「拿到音频之后怎么稳定地转成文字」。两者的失败模式完全不同——
抓取失败是网络或解析器改版，识别失败是模型退化或切点不当。混在一起，
排查时无法判断是哪一边出的问题。

边界（与 `layer_rules.toml` 一致）：**不碰数据库**。本层只吃音频样本、
吐文本与时间段，落库由调用方（worker）通过 `kb.store` 做。

为什么必须分段（2026-11-27 实测，448 秒中文语音，SenseVoice int8）：

| 方式 | 耗时 | RTF | 结果 |
|---|---|---|---|
| 整段解码 | 70.79 s | 0.158 | 「晚到 1 分钟」「晚到十0分钟」「路上有点毒」——数字与同音字都错 |
| 30 秒分段 | 10.78 s | 0.024 | 全部正确、标点齐全 |

所以分段的目的**不是省时间**，是准确率。速度顺带快了 6.6 倍。
"""
